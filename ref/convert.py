"""Convert a llama2.c fp32 checkpoint (version 0 .bin) into the flat FPGA weight file.

  python convert.py model.bin model.flat [--hex model.hex]

Outputs:
  model.flat        the flat file described in layout.py (this is what gets copied into HBM)
  model.flat.json   header fields + byte offsets, for the host program and testbenches
  model.flat.vh     Verilog localparams with the same numbers, for the RTL
  --hex file        one 32-bit word per line, for $readmemh in a simulation memory model
"""
import argparse
import json
import numpy as np
import layout
from reference import load_llama2c


def main():
    """Command line: llama2.c checkpoint in, flat weight file (plus .json, .vh and optional .hex) out."""
    p = argparse.ArgumentParser()
    p.add_argument("src")
    p.add_argument("dst")
    p.add_argument("--hex")
    a = p.parse_args()

    cfg, w = load_llama2c(a.src)
    o = layout.compute(cfg)
    buf = bytearray(o["total"])
    buf[: layout.HEADER_BYTES] = layout.pack_header(cfg, o)

    def put(off, arr):
        arr = np.ascontiguousarray(arr, dtype="<f4")
        buf[off: off + arr.nbytes] = arr.tobytes()

    put(o["tok_emb"], w["tok_emb"])
    for l in range(cfg["n_layers"]):
        base = o["layers_start"] + l * o["layer_stride"]
        for name, shape in layout.layer_tensors(cfg):
            arr = w[name][l]
            assert arr.shape == shape, (name, arr.shape, shape)
            put(base + o["layer_rel"][name], arr)
    put(o["final_norm"], w["rms_final"])
    put(o["rope_cos"], w["rope_cos"])
    put(o["rope_sin"], w["rope_sin"])
    if not cfg["shared"]:
        put(o["wcls"], w["wcls"])

    with open(a.dst, "wb") as f:
        f.write(buf)

    info = dict(config=cfg, offsets={k: v for k, v in o.items() if k != "layer_rel"}, layer_rel=o["layer_rel"])
    with open(a.dst + ".json", "w") as f:
        json.dump(info, f, indent=2)

    with open(a.dst + ".vh", "w") as f:
        f.write("// generated by convert.py - byte offsets into the flat weight file\n")
        for k, v in cfg.items():
            f.write(f"localparam {k.upper()} = {int(v)};\n")
        for k, v in info["offsets"].items():
            f.write(f"localparam OFF_{k.upper()} = {v};\n")
        for k, v in o["layer_rel"].items():
            f.write(f"localparam LREL_{k.upper()} = {v};\n")

    if a.hex:
        words = np.frombuffer(bytes(buf), dtype="<u4")
        with open(a.hex, "w") as f:
            f.write("\n".join(f"{x:08x}" for x in words) + "\n")

    print(f"wrote {a.dst} ({o['total']} bytes), layer stride {o['layer_stride']} bytes")


if __name__ == "__main__":
    main()
